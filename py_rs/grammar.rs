pub fn rule_arg_offset(rule_id: u8) -> usize {
    let mut off = RULE_ARG_OFFSET_TABLE[rule_id as usize] as usize;
    if rule_id >= FIRST_RULE_WITH_OFFSET_ABOVE_255 {
        off |= 0x100;
    }
    off
}

pub fn rule_arg(rule_id: u8) -> &'static [u16] {
    let off = rule_arg_offset(rule_id);
    let end = if (rule_id as usize + 1) < RULE_ARG_OFFSET_TABLE.len() {
        rule_arg_offset(rule_id + 1)
    } else {
        RULE_ARG_COMBINED_TABLE.len()
    };
    &RULE_ARG_COMBINED_TABLE[off..end]
}
